  // Set initial Mermaid theme based on current theme
  function initMermaidTheme() {
    var storageKey = 'workspace-tasks-docs-theme';
    var currentTheme = 'dracula';

    try {
      var stored = localStorage.getItem(storageKey);
      if (stored && mermaidThemes[stored]) {
        currentTheme = stored;
      }
    } catch (e) {
      // localStorage not available, use default
    }

    window.MermaidThemeVariables = mermaidThemes[currentTheme] || mermaidThemes.dracula;
  }

  // Expose theme map globally so theme.js can use it
